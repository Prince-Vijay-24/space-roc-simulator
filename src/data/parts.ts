export function getPartWidth(part: PlacedPart, def?: PartDefinition): number {
  const isEngine = def?.category === 'Propulsion' || def?.isSRB || (def?.maxThrust ?? 0) > 0 || !!part.engineConfig;
  const isCommand = def?.category === 'Command';
  const isUtilityFixed = def?.isLandingLeg || def?.isWheel || def?.isParachute || def?.isRCS || def?.isDockingPort;

  // Rigid authentic engines and command capsules maintain defined scale
  if (isEngine) {
    const sizeFactor = part.engineConfig
      ? Math.max(0.25, Math.min(2.0, (part.engineConfig.engineSizePercent || 50) / 50))
      : 1.0;
    return Math.round((def?.width ?? 2.0) * sizeFactor * 100) / 100;
  }

  // Dynamic Solar Panel Sizing (Grid N x cell width, scale multiplier)
  if (def?.isSolarPanel) {
    const scale = part.solarScale ?? 1.0;
    const gridN = part.solarGridN || def.solarGridN || 2;
    const cellW = part.solarCellWidthM ?? 0.45;
    const baseW = Math.max(def.width || 1.2, gridN * cellW * 1.5);
    return Math.round(baseW * scale * 100) / 100;
  }

  if (isCommand || isUtilityFixed) {
    return def?.width ?? 2.0;
  }

  // Procedural tanks, cones, adapters, and fairings
  if (part.customWidth !== undefined && part.customWidth > 0) return part.customWidth;
  return def?.width ?? 2.0;
}

export function getPartHeight(part: PlacedPart, def?: PartDefinition): number {
  const isEngine = def?.category === 'Propulsion' || def?.isSRB || (def?.maxThrust ?? 0) > 0 || !!part.engineConfig;
  const isCommand = def?.category === 'Command';
  const isUtilityFixed = def?.isLandingLeg || def?.isWheel || def?.isParachute || def?.isRCS || def?.isDockingPort;

  if (isEngine) {
    const sizeFactor = part.engineConfig
      ? Math.max(0.25, Math.min(2.0, (part.engineConfig.engineSizePercent || 50) / 50))
      : 1.0;
    const lengthFactor = part.engineConfig
      ? Math.max(0.2, Math.min(2.0, (part.engineConfig.nozzleLengthPercent || 100) / 100))
      : 1.0;
    return Math.round((def?.height ?? 2.0) * sizeFactor * (0.35 + 0.65 * lengthFactor) * 100) / 100;
  }

  // Dynamic Solar Panel Height (Grid M x cell height + outward boom extension distance)
  if (def?.isSolarPanel) {
    const scale = part.solarScale ?? 1.0;
    const gridM = part.solarGridM || def.solarGridM || 4;
    const cellH = part.solarCellHeightM ?? 0.65;
    const boomM = part.solarBoomLengthM ?? 0.0;
    const baseH = Math.max(def.height || 2.4, gridM * cellH) + boomM;
    return Math.round(baseH * scale * 100) / 100;
  }

  if (isCommand || isUtilityFixed) {
    return def?.height ?? 2.0;
  }

  // Procedural tanks & scalable structural adapters
  if (part.customHeight !== undefined && part.customHeight > 0) return part.customHeight;
  return def?.height ?? 2.0;
}

export function getPartSnapPoints(part: PlacedPart, def: PartDefinition) {
  const w = getPartWidth(part, def);
  const h = getPartHeight(part, def);
  
  if (def.category === 'Fuel' || part.partId === 'custom_fuel_tank' || def.isOreTank) {
    return [
      { x: 0, y: h * 0.5, type: 'top' as const },
      { x: 0, y: -h * 0.5, type: 'bottom' as const },
      { x: -w * 0.5, y: 0, type: 'side' as const },
      { x: w * 0.5, y: 0, type: 'side' as const },
    ];
  }

  if (def.category === 'Propulsion' || part.partId === 'modular_rocket_engine') {
    return [
      { x: 0, y: h * 0.5, type: 'top' as const },
      { x: 0, y: -h * 0.5, type: 'bottom' as const },
    ];
  }

  // Scale existing snap points proportionally if the part has custom dimensions or engine config
  if (part.customWidth !== undefined || part.customHeight !== undefined || part.engineConfig) {
    const scaleX = def.width > 0 ? w / def.width : 1;
    const scaleY = def.height > 0 ? h / def.height : 1;
    return def.snapPoints.map((sp) => ({
      ...sp,
      x: sp.x * scaleX,
      y: sp.y * scaleY,
    }));
  }

  return def.snapPoints;
}

