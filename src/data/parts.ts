export const PART_CATALOG: Record<string, PartDefinition> = new Proxy(basePartCatalog, {
  get(target, prop: string | symbol) {
    if (typeof prop === 'string') {
      if (prop in target) return target[prop];
      if (PART_ALIASES[prop] && target[PART_ALIASES[prop]]) {
        return target[PART_ALIASES[prop]];
      }
    }
    return (target as any)[prop];
  },
  has(target, prop: string | symbol) {
    if (typeof prop === 'string') {
      return prop in target || (prop in PART_ALIASES && PART_ALIASES[prop] in target);
    }
    return prop in target;
  },
});

